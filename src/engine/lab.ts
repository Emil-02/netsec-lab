import type { Network } from "./core/network";
import type { BackgroundJob } from "./shell/types";
import type { TopologySpec } from "./topology";

export interface LabContext {
  net: Network;
  /** Every fact observed since the lab started. */
  facts: Set<string>;
  /** Facts produced by the most recent action only (use for "do X after Y" objectives). */
  recent: Set<string>;
}

export interface Objective {
  id: string;
  text: string;
  check: (ctx: LabContext) => boolean;
  /** Objectives that must already be complete before this one can be completed. */
  requires?: string[];
}

/**
 * Objectives are sticky: once complete they stay complete. An objective with
 * `requires` is only evaluated after its prerequisites are done.
 */
export function evaluateObjectives(objectives: Objective[], ctx: LabContext, done: Iterable<string>): string[] {
  const completed = new Set(done);
  let changed = true;
  while (changed) {
    changed = false;
    for (const o of objectives) {
      if (completed.has(o.id)) continue;
      if (o.requires?.some((r) => !completed.has(r))) continue;
      if (o.check(ctx)) {
        completed.add(o.id);
        changed = true;
      }
    }
  }
  return objectives.filter((o) => completed.has(o.id)).map((o) => o.id);
}

export type Difficulty = "pemula" | "menengah" | "mahir";

export interface LabDefinition {
  id: string;
  title: string;
  summary: string;
  difficulty: Difficulty;
  estimatedMinutes: number;
  xp: number;
  topology: TopologySpec;
  /** Devices the learner can open a terminal on; the first one is the default. */
  controllable: string[];
  allowedCommands?: string[];
  /** Traffic generated by simulated users while the learner listens (e.g. with tcpdump). */
  background?: BackgroundJob[];
  briefing: string[];
  objectives: Objective[];
  hints: string[];
}
